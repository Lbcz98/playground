/**
 * `npm run guides:build` — writes web/protos/generated/tokens.md, rules.md and explore-tokens.md, the
 * reference a designer's Claude Code reads, from tokens/tokens.json and rules.ts.
 *
 * `npm run guides:check` (`--check`) writes nothing and exits 1 when a committed
 * file differs from regeneration. `npm run tokens:check` runs it too.
 * Output is sorted, so the order of entries in either source does not matter.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { RULES } from '../src/shared/design-system/rules'
import { ruleScope } from '../src/shared/design-system/deviations'
import { COMMENT_TAGS } from '../src/shared/export/commentGrammar'
import { hexWithAlpha, isAlpha } from '../src/shared/design-system/color-alpha'
import { GRID_SPACING } from '../src/primitives/tokens'
import { contentCardSpec } from '../src/design-system/primitives'
import { collectTokens, CSS_EXTENSION, cssVarName, NAME_FAMILIES, textClassName, TOKENS_SOURCE } from './tokens/compile'

export const GUIDE_FILES = {
  tokens: 'web/protos/generated/tokens.md',
  rules: 'web/protos/generated/rules.md',
  explore: 'web/protos/generated/explore-tokens.md',
} as const

const HEADER =
  '<!-- GENERATED by scripts/build-guides.ts from tokens/tokens.json and src/shared/design-system/rules.ts. Do not edit; run npm run guides:build. -->'

/** Families with a prop type the kit declares by hand in `src/primitives/tokens.ts` (SizeRole, RadiusRole). */
const EXTRA_FAMILIES = [
  { type: 'SizeRole', prefix: '--dimension-size-semantic-' },
  { type: 'RadiusRole', prefix: '--dimension-radius-semantic-' },
]

const cmp = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0)
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

type Json = Record<string, unknown>
type Tok = ReturnType<typeof collectTokens>[number]

function resolver(root: unknown) {
  const all = collectTokens(root as Json)
  const byPath = new Map(all.map((t) => [t.path.join('.'), t]))
  const resolve = (v: unknown, seen: string[] = []): unknown => {
    if (typeof v === 'string') {
      const m = /^\{([^}]+)\}$/.exec(v)
      if (!m) return v
      if (seen.includes(m[1])) throw new Error(`alias cycle at ${m[1]}`)
      const target = byPath.get(m[1])
      return target && literalOf(target, [...seen, m[1]])
    }
    if (Array.isArray(v)) return v.map((x) => resolve(x, seen))
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolve(x, seen)]))
    return v
  }
  /** A token's resolved value; an alpha variant shows the `#RRGGBBAA` of its base, not the bare base. */
  const literalOf = (t: Tok, seen: string[] = []): unknown => {
    const value = resolve(t.value, seen)
    const hint = t.extensions?.[CSS_EXTENSION]
    const alpha = hint && typeof hint === 'object' ? (hint as Json).alpha : undefined
    return typeof value === 'string' && isAlpha(alpha) ? (hexWithAlpha(value, alpha) ?? value) : value
  }
  const json = (v: unknown): string => JSON.stringify(v, (_, x) => (x && typeof x === 'object' && !Array.isArray(x) ? Object.fromEntries(Object.entries(x).sort(([a], [b]) => cmp(a, b))) : x))
  /** A value as a reader takes it in: a text style as `size / line height · weight · tracking`, a gradient as its stops. */
  const show = (v: unknown): string => {
    if (typeof v === 'string') return v
    const o = v as Record<string, unknown>
    if (o && typeof o === 'object' && 'fontSize' in o) return `${o.fontSize} / ${o.lineHeight} · ${o.fontWeight} · ${o.letterSpacing}`
    if (Array.isArray(v) && v.every((x) => x && typeof x === 'object' && 'color' in x && 'position' in x)) return v.map((x) => `${x.color} ${Math.round(Number(x.position) * 100)}%`).join(', ')
    return json(v)
  }

  return { all, literalOf, show }
}

function tokensGuide(root: unknown): string {
  const { all, literalOf, show } = resolver(root)
  const screenName = (t: Tok): string => {
    const css = cssVarName(t.path)
    if (t.type === 'typography') return `\`Text variant="${textClassName(t.path).replace(/^text-/, '')}"\``
    for (const f of [...NAME_FAMILIES, ...EXTRA_FAMILIES]) {
      if (!css.startsWith(f.prefix)) continue
      const name = css.slice(f.prefix.length)
      const asText = f.type === 'StatusColor' ? ` or \`TextColor\` \`status-${name}\`` : ''
      return `\`${f.type}\` \`${name}\`${asText}`
    }
    return ''
  }

  const groups = new Map<string, Tok[]>()
  for (const t of all) {
    if (t.path.includes('core')) continue // core tokens exist only for other tokens to point at
    if (!screenName(t)) continue // no kit prop takes it: an HTML exploration finds it in explore-tokens.md
    const g = t.path.slice(0, 2).join('.')
    groups.set(g, [...(groups.get(g) ?? []), t])
  }
  const out = [
    HEADER,
    '',
    '# Tokens',
    '',
    'The tokens a screen can name: "Screen name" is the value a kit prop takes (its type in `src/primitives/token-names.ts` or `tokens.ts`). Core tokens, and tokens no kit prop takes (gradients, motion, some colours), are not here: a screen cannot name them. Text styles read `size / line height · weight · letter spacing`, in Inter.',
    'Spacing and radius steps are core scales: use the `GridSpacing` and `RadiusStep` props of the kit.',
  ]
  for (const g of [...groups.keys()].sort(cmp)) {
    out.push('', `## ${g}`, '', '| Path | Value | Screen name |', '| --- | --- | --- |')
    for (const t of groups.get(g)!.sort((a, b) => cmp(a.path.join('.'), b.path.join('.')))) {
      out.push(`| \`${t.path.join('.')}\` | ${cell(show(literalOf(t)))} | ${cell(screenName(t))} |`)
    }
  }
  return out.join('\n') + '\n'
}

/** The core scales and type parts, by CSS name: what an HTML exploration (no kit props) writes in `var()`. */
function exploreGuide(root: unknown): string {
  const { all, literalOf, show } = resolver(root)
  const out = [
    HEADER,
    '',
    '# Tokens for HTML explorations only',
    '',
    'For `docs/explorations/<slug>/index.html`, written as plain HTML with `var(--name)`: every kit variable an option uses is here. A `/proto` screen never uses this file: it takes `tokens.md` and the kit props (`GridSpacing`, `RadiusStep`, `Text`), not raw core variables.',
    '"Prop step" is the value the kit prop of that name takes.',
  ]
  const table = (title: string, rows: string[][], head = ['CSS variable', 'Value', 'Prop step']): void => {
    out.push('', `## ${title}`, '', `| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`)
    for (const r of rows) out.push(`| ${r.map(cell).join(' | ')} |`)
  }
  const by = (pred: (t: Tok) => boolean, step: (name: string) => string = () => ''): string[][] =>
    all
      .filter(pred)
      .map((t) => [`\`${cssVarName(t.path)}\``, show(literalOf(t)), step(t.path[t.path.length - 1])])
      .sort((a, b) => cmp(a[0].replace(/[^-]*$/, ''), b[0].replace(/[^-]*$/, '')) || parseFloat(a[1]) - parseFloat(b[1]) || cmp(a[0], b[0])) // by family, then by value: order-independent
  const core = (f: string) => (t: Tok) => t.path.join('.').startsWith(`dimension.${f}.core.`)
  /** A family's non-core tokens by CSS name: values of mixed kinds (hex, ms, objects) have no order of their own. */
  const named = (family: string): string[][] => by((t) => t.path[0] === family && !t.path.includes('core')).map((r) => r.slice(0, 2)).sort((a, b) => cmp(a[0], b[0]))
  table('Colours', named('color'), ['CSS variable', 'Value'])
  table('Spacing', by(core('spacing'), (n) => (GRID_SPACING.includes(n as never) ? `\`GridSpacing\` \`${n}\`` : 'off the layout grid: no prop')))
  table('Radius', by(core('radius'), (n) => `\`RadiusStep\` \`${n}\``))
  table('Component sizes, radii and insets', by((t) => /^--dimension-(size|radius|spacing)-semantic-/.test(cssVarName(t.path))).map((r) => r.slice(0, 2)), ['CSS variable', 'Value'])
  out.push(
    '',
    '## Surfaces: which tokens a card takes',
    '',
    'A card, a panel or any box that holds an option is one of the kit\'s surfaces. The same role looks the same in every option of an exploration: same radius, same color, same inset. `scripts/check-explore-layout.mjs` measures this on the rendered page.',
    '',
    '| Surface | Radius | Inset (padding, all sides) | Width (fixed) | Color |',
    '| --- | --- | --- | --- | --- |',
    '| Card | `--dimension-radius-semantic-card` | `--dimension-spacing-semantic-card-inset` | `--dimension-size-semantic-card-width`, `-card-height` | `--color-semantic-functional-background-elevated` |',
    '| Expanded card, Content Card (tall panel, at most 456px high) | `--dimension-radius-semantic-content-card` | `--dimension-spacing-semantic-card-inset-expanded` (the Content Card\'s `lg`, 24px) | `--dimension-size-semantic-card-expanded-width`, `--dimension-size-semantic-content-card-width` | `--color-semantic-functional-background-elevated` |',
    '| Pill (a glance bar, a chip) | `--dimension-radius-semantic-pill`, only up to two controls tall (`--dimension-size-semantic-control-height-lg`) | `--dimension-spacing-core-2xs` or `-xs` | hugs its content | `--color-semantic-functional-background-elevated` |',
    '',
    `- Width is the kit's, never squeezed: no \`max-width\`, no percentage. Height hugs the content, never a fixed \`height\`, and stops at ${contentCardSpec.maxHeight}px (the tallest a kit card may be).`,
    '- A panel of an option is a Card or a Content Card, never a new radius (12, 16, 20…). Rows and chips inside it take a smaller `--dimension-radius-core-*` step than the surface.',
    '- The dark area behind the panel (`--color-semantic-functional-background-primary`) is the TV, not a card: it takes no card radius and counts as no surface.',
    '- The inset is at least the one in the table: a 40px radius with a 16px inset leaves text hugging the curve.',
    '- Pick one surface for the whole exploration. Using the other on purpose (say, a Content Card beside small cards) is the idea of that option, not a style choice.',
    '- An option whose idea is not a card (a ring, a map, a strip) marks the shape with `data-surface="own"` and says why in the report.',
  )
  table('Border width', by(core('border-width')).map((r) => r.slice(0, 2)), ['CSS variable', 'Value'])
  table('Opacity', named('opacity'), ['CSS variable', 'Value'])
  table('Gradients', named('gradient'), ['CSS variable', 'Stops'])
  table('Motion', named('motion'), ['CSS variable', 'Value'])
  table('Type parts', by((t) => t.path[0] === 'typography' && t.type !== 'typography').map((r) => r.slice(0, 2)), ['CSS variable', 'Value'])
  const text = all.filter((t) => t.type === 'typography')
  table(
    'Type classes (`.text-*`)',
    text.sort((a, b) => cmp(textClassName(a.path), textClassName(b.path))).map((t) => {
      const v = literalOf(t) as Record<string, unknown>
      return [`\`.${textClassName(t.path)}\``, ...['fontSize', 'fontWeight', 'letterSpacing', 'lineHeight'].map((k) => String(v[k]))]
    }),
    ['Class', 'Size', 'Weight', 'Letter spacing', 'Line height'],
  )
  return out.join('\n') + '\n'
}

interface RuleLike {
  id: string
  title: string
  statement: string
  flexibility: string
  appliesTo?: readonly string[]
}

function rulesGuide(rules: readonly RuleLike[], scope: (id: string) => string = ruleScope): string {
  const out = [HEADER, '', '# Rules', '']
  const titles = { law: 'Laws (never bypassable)', pattern: 'Patterns (breakable in Exploratory mode, declared)', convention: 'Conventions (breaking one only produces a note)' }
  for (const level of ['law', 'pattern', 'convention'] as const) {
    out.push(`## ${titles[level]}`, '')
    for (const r of rules.filter((x) => x.flexibility === level).sort((a, b) => cmp(a.id, b.id))) {
      out.push(`### \`${r.id}\` ${r.title}`, '', r.statement, '')
      if (r.appliesTo?.length) out.push(`Applies to: ${r.appliesTo.map((c) => `\`${c}\``).join(', ')}`, '')
    }
  }
  out.push('## How to declare', '')
  for (const c of COMMENT_TAGS) {
    out.push(`### \`${c.tag}\``, '', `Form: \`${c.form}\``, '', c.meaning, '', `- On a node: ${c.node}`, `- On the screen: ${c.screen}`, '')
  }
  const patterns = rules.filter((r) => r.flexibility === 'pattern').map((r) => r.id)
  const list = (s: string): string => patterns.filter((id) => scope(id) === s).sort(cmp).map((id) => `\`${id}\``).join(', ') || 'none'
  out.push(
    '### Where each pattern is declared',
    '',
    `- On the node where it breaks (a screen-level declaration is an error): ${list('node')}`,
    `- On the screen, or on the root node: ${list('screen')}`,
    '',
  )
  return out.join('\n').replace(/\n+$/, '\n')
}

export function buildGuides(tokensJson: unknown, rules: readonly RuleLike[] = RULES as unknown as RuleLike[]) {
  return { tokens: tokensGuide(tokensJson), rules: rulesGuide(rules), explore: exploreGuide(tokensJson) }
}

function main(): void {
  const ROOT = fileURLToPath(new URL('..', import.meta.url))
  const check = process.argv.includes('--check')
  const built = buildGuides(JSON.parse(readFileSync(join(ROOT, TOKENS_SOURCE), 'utf8')))
  const stale: string[] = []
  for (const key of ['tokens', 'rules', 'explore'] as const) {
    const file = join(ROOT, GUIDE_FILES[key])
    let current = ''
    try {
      current = readFileSync(file, 'utf8')
    } catch {
      // Missing counts as stale.
    }
    if (current === built[key]) continue
    stale.push(GUIDE_FILES[key])
    if (!check) {
      mkdirSync(join(file, '..'), { recursive: true })
      writeFileSync(file, built[key])
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`Stale guide — run \`npm run guides:build\`:\n${stale.map((f) => `  ${f}`).join('\n')}`)
      process.exit(1)
    }
    console.log('Guides are up to date with tokens.json and rules.ts.')
  } else {
    console.log(stale.length ? `Wrote ${stale.join(', ')}` : 'Guides already up to date.')
  }
}

if (!process.env.VITEST) main()
